export type EnglishLevelId = 'grade3' | 'basic' | 'intermediate' | 'expert';

export interface VocabularyWord {
  id: string;
  english: string;
  indonesian: string;
  category: string;
  emoji: string;
  pronunciationHint: string;
  exampleSentence: string;
  sentenceMeaning: string;
}

export interface TenseExample {
  title: string;
  formula: string;
  description: string;
  timeline: 'past' | 'present' | 'continuous';
  sentence: string;
  translation: string;
  verbForm: string; // e.g. "V1 (eat)", "V-ing (is eating)", "V2 (ate)"
  timeSignal: string; // e.g. "Every day", "Right now", "Yesterday"
}

export interface EnglishTopic {
  id: string;
  title: string;
  subtitle: string;
  badge: string;
  icon: string;
  description: string;
  kikoTip: string;
  vocabularies: VocabularyWord[];
  grammarFocus?: {
    title: string;
    rules: string[];
    tenseComparisons?: TenseExample[];
  };
  conversation?: {
    characterA: string;
    characterB: string;
    dialogue: { speaker: string; text: string; meaning: string }[];
  };
}

export interface EnglishQuizQuestion {
  id: string;
  level: EnglishLevelId;
  question: string;
  soundText?: string;
  options: string[];
  correctAnswer: string;
  explanation: string;
  tip: string;
}

export interface EnglishLevel {
  id: EnglishLevelId;
  name: string;
  tagline: string;
  symbol: string;
  badgeColor: {
    bg: string;
    text: string;
    border: string;
    accent: string;
  };
  topics: EnglishTopic[];
  quizQuestions: EnglishQuizQuestion[];
}

